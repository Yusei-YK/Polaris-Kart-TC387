/*=========================== 【重要】纵向为什么不用绝对测距 ===========================*/
/* 单目按宽度反算距离 dist = W_real * f_px / W_px 成立需要三个前提：
 *   刚性、正对镜头、完整可见。
 * 而规则要求标志板【贴在人身上】，这三条同时不成立：
 *   人走动时身体摆动 → 板面旋转，投影宽度按 cos 缩；
 *   柔性纸/布跟随身体曲面 → 板面弯曲，投影宽度无固定物理含义；
 *   手臂/身体遮挡、人侧身 → 宽度突然掉一大截。
 * 实算过量级：侧身 60° 时投影宽只剩约 0.5 倍，绝对测距会把 1.5m 报成 3m。
 * 对这样的观测量做卡尔曼融合只是把错误值平滑，不会让它变准 ——
 * 首版加过的距离 KF 已按此理由整段删除。
 *
 * 【改成什么 —— 2026-08-10 二次修正：纵向【完全不闭环】】
 *   上一版改成了"尺度比三档 → 速度增量 ±0.3m/s"。这一版把它整个撤掉。
 *
 *   撤的理由：scale_r 是整条视觉链里【最脆】的观测量 ——
 *     目标可形变、身体旋转、FB 一致性校验还是单金字塔近似，
 *     它的噪声量级和"真实距离变化"是同一个数量级。
 *   把这种量接进执行机构，等于让噪声直接调油门；更糟的是它和光流噪声
 *   同源，容易耦合出"加速→尺度变大→减速→尺度变小→加速"的速度自激振荡。
 *
 *   而这个任务里【人是队友，不是被动目标】：人本来就会主动配合保持距离。
 *   与其让车用最烂的观测量去猜距离，不如把这个自由度交给人 ——
 *   人的眼睛和腿构成的"距离控制器"，带宽和可靠性都远超单目尺度估计。
 *
 *   所以纵向策略变成：
 *       车 = 固定巡航速度（FOLLOW_V_CRUISE_MS）
 *       人 = 自己走快走慢，维持与车的距离
 *   横向仍然闭环（车必须自己对准人），因为方位角来自质心中值，
 *   是整条链里【最稳】的观测量，和 scale 完全不是一个可靠性等级。
 *
 *   scale_level / scale_r 仍然计算并输出，但【只作为观测量上报】，
 *   不参与调速 —— 留着是为了调试时能看出人车距离在怎么漂。
 *   唯一例外是下面的近距安全联锁，那是刹车，不是控制。
 *
 * 【横向怎么办】
 *   纯跟踪 kappa = 2*sin(beta)/L 里的 L 是前视距离，原来喂的是实测距离。
 *   现在改喂固定标称值 FOLLOW_L_NOMINAL_M。这等价于把转向律降为
 *   "对方位角成比例"，而方位角来自质心、不依赖板宽，是可靠观测量。
 *   固定 L 的代价是近处转向偏软、远处偏硬，由方位角减速一并兜住。 */

/*=========================== 纯跟踪前视距离（固定标称值）===========================*/
/* L_NOMINAL：纯跟踪公式 kappa = 2*sin(beta)/L 里的 L。
 * 原先喂的是实测距离 dist，现已证明对身体挂载的柔性板不可行（见文件头【重要】
 * 纵向为什么不用绝对测距）。改为固定标称值，等价于把转向律降为"对方位角成比例"。
 *
 * 取 1.5m：这是期望跟车距离的中点。固定 L 的代价是近处转向偏软、远处偏硬，
 * 由方位角减速兜住（BEARING_SLOW_DEG 在近处大角度时压速度，换取转向余量）。 */
#define FOLLOW_L_NOMINAL_M         (1.50f)

/*=========================== 纵向策略：两套方案，编译期二选一 ===========================*/
/* 两套都保留，不删。理由：哪套在实车上更好【只能实测】，而实测需要能一键切回去对比。
 *
 *   FIXED  车恒速巡航，距离交给人维持。scale 完全不进控制。
 *          优点：不依赖最脆的观测量，无速度振荡风险，行为可预测。
 *          缺点：要求人主动配合；人不配合时只能靠近距联锁刹车。
 *
 *   SCALE  车按尺度比三档加减速，自己维持距离。
 *          优点：人可以随便走，车自己跟。演示效果好。
 *          缺点：scale_r 噪声直接进油门；存在
 *                "加速→尺度变大→减速→尺度变小→加速" 的自激振荡风险。
 *                这个风险是理论推断，【实车没测过】—— 也许 ±10% 死区
 *                加上 0.3m/s 的粗粒度已经把它压住了。所以不预先否掉。
 *
 * 现场建议顺序：先用 FIXED 保证能完赛，再试 SCALE 看能不能更好。
 * 切换只改这一个宏，两套的参数各自独立，互不影响。 */
#define FOLLOW_LON_FIXED           (0)     /* 恒速巡航，人控距离 */
#define FOLLOW_LON_SCALE           (1)     /* 尺度比三档，车控距离 */

#ifndef FOLLOW_LON_MODE
#define FOLLOW_LON_MODE            (FOLLOW_LON_FIXED)
#endif

/*---------------------- 方案 FIXED 的参数 ----------------------*/
/* 跟随段的巡航速度(m/s)。车恒定以此速度前进，不因视觉尺度变化而加减速。
 *
 * 取 1.0 m/s 的依据：
 *   成年人正常步速 1.2-1.4 m/s，快走 1.8 m/s。取 1.0 略低于正常步速，
 *   这样人只需要"稍微放慢"就能维持距离，而不是被车追着必须快走 ——
 *   人在小心走路（要回头看车、要保持板子朝向镜头）时步速本来就会下降。
 *   宁可慢，稳定完赛优先。实车按队友的实际步速改这一个数。
 *
 * 2026-08-13 本地视觉方案从 0.70 提到 1.10：接近成年人正常步速，
 *   同时保留现场跟随和人工急停余量。
 *
 * 【改这个数时必须一起验的下限】
 *   方位角减速最狠会乘 SLOW_MIN_RATIO(0.35)，而小于 V_MIN_MS(0.25) 的
 *   速度是小占空比堵转区（发热不出力，见 V_MIN_MS 处注释）。
 *   1.00 × 0.35 = 0.35 > 0.25，原来安全；
 *   1.10 × 0.40 = 0.44 > 0.25，不会跌进堵转区。
 *   而 FIXED 分支【没有】像 SCALE 分支那样的死区抬升（kart_follow.c:252
 *   那段在 #if SCALE 里），所以不能指望它兜底。
 *   SLOW_MIN_RATIO 保持 0.40：1.10 × 0.40 = 0.44 > 0.25。
 *   以后再改巡航速度，先算这一乘。 */
#define FOLLOW_V_CRUISE_MS         (1.10f)

/*---------------------- 方案 SCALE 的参数 ----------------------*/
/* kart_vtrack 给出的 scale_level 三档对应的速度增量（m/s）：
 *   TOO_NEAR  → 减速（人靠近了 / 车追过头）
 *   NORMAL    → 保持当前速度（尺度比在 0.9-1.1 死区内）
 *   TOO_FAR   → 加速追（人走远了 / 车落后了）
 *
 * 取 ±0.3 m/s：从 NORMAL 到 FAR 一档约 1 秒补上 0.3m 相对位移，
 * 响应不激进也不滞后。三档是离散的，不存在死区边界的连续抖动。
 * 【调试要点】若实车出现速度周期性起伏（自激振荡），先把这个数往小调，
 * 再考虑加宽 kart_vtrack 的 SCALE_NEAR/FAR_THRESH 死区。 */
#define FOLLOW_SCALE_V_DELTA_MS    (0.30f)

/* SCALE 方案的速度上下限。FIXED 方案不用这两个（速度只有 V_CRUISE 一个值）。
 * 上限按人的步速定，不是按车的能力定 —— 车本身能跑 2.6 m/s。
 * 下限避免长期小占空比堵转发热；注意是"抬到 V_MIN"而不是"压到 0"，
 * 否则会在死区外边界多出一段"想走又走不动"的死区。 */
#define FOLLOW_V_MAX_MS            (1.80f)
#define FOLLOW_V_MIN_MS            (0.25f)

/* SCALE 方案下目标太近时是否允许倒退。默认否 ——
 * 人停下、车滑到很近时后退，会在人前后来回蠕动；
 * 而且倒车时摄像头朝前看不见人，属于开环。停住等人走远更稳。 */
#define FOLLOW_ALLOW_REVERSE       (0)

/*---------------------- 两套共用 ----------------------*/
/* 速度斜率(m/s per 10ms 拍)。0.04 → 0.25s 从 0 升到 1.0。
 * 不做速度阶跃：阶跃会让后轮瞬间打滑、车头一甩，而车头一甩方位角观测跟着抖，
 * 视觉是唯一的横向反馈源，不能让执行机构去污染它。
 * FIXED 用它做起停过渡；SCALE 用它平滑三档之间的跳变。 */
#define FOLLOW_V_RAMP              (0.04f)

/*=========================== 近距安全联锁（不是控制器）===========================*/
/* 【这不是调速，是刹车】
 *   固定速度方案的前提是"人会配合"。但人可能突然停下、转身找东西、摔倒。
 *   这时固定速度的车会直接顶上去 —— 属于安全问题，不是性能问题。
 *   所以保留一个【二值联锁】：尺度比超过硬阈值就停车，低于恢复阈值再走。
 *   它只有"走/停"两个状态，不参与任何连续调速，因此不会引入速度振荡。
 *
 * 阈值取 1.35：远高于 kart_vtrack 的 SCALE_NEAR_THRESH(1.10)。
 *   1.10 那个档位是给"轻微靠近"用的，噪声能碰到；1.35 意味着目标像素尺寸
 *   涨了 35%，对应距离缩到约 74%（1.5m → 1.1m），这个幅度 scale 噪声打不出来。
 *   宁可迟一点刹，也不要因为噪声在正常跟随中途无故停车。
 *
 * 恢复阈值 1.15：留 0.20 回差，防止在阈值附近走-停-走抖动。 */
/* 2026-08-17 停车距离 0.90m -> 0.70m(用户要求再拉近)。
 * scale_r 是尺度比不是距离，基准 1.50m: 1.35x1.11 = 1.15x1.30 = 1.50。
 * 0.70m -> 1.50/0.70 = 2.143; RESUME 0.85m -> 1.50/0.85 = 1.765。
 * 回差保持 0.15m 距离间隔，但 scale_r 是非线性的 1/d，格距离越近回差越宽:
 * 2.14-1.76=0.38(原 0.24)，越近抗动余量越大，不是坏事。
 * 【必须两个一起改】只改 STOP 不改 RESUME，车停下后人得退更远才走。
 * 【联动第三处】kart_person_link.h 的 SCALE_R_STOP 必须跟着抬到 2.19，
 * 否则灯板那条 height 刹车路径推不动 scale_r 过停车线，整条路径失效。 */
#define FOLLOW_NEAR_STOP_ENABLE    (1)
#define FOLLOW_NEAR_STOP_R         (2.14f)
#define FOLLOW_NEAR_RESUME_R       (1.76f)

/* 联锁触发需要连续多少拍。单帧尺度尖峰不该导致刹车。
 * 3 拍 = 30ms，仍远快于人走 0.03m 的时间，安全性不受影响。 */
/* 【2026-08-16 从 3 拍改成 2 帧,名字也从 TICKS 改成 FRAMES】
 * 上面那段"3 拍 = 30ms"在视觉同步跑、30FPS 时成立。搬到 core3 后单帧约 360ms,
 * 而 kart_follow_update 仍是每 10ms 拍调一次 —— 同一帧的 scale_r 会被连续读约 36 次,
 * 3 拍在同一帧内就数满,等于【单帧尖峰直接刹车】,恰好是上面那段声称要防的事。
 *
 * 【为什么单帧尖峰真的会发生】dist_m 由框高反算(f_px=83.5,板高 0.45m):
 *   NEAR_STOP_R=1.35 -> dist 1.11m -> 框高 33.8px
 *   框高 +-1px       -> dist 1.08/1.15m -> scale_r 1.39/1.30
 * 【1 个像素的量化噪声就能跨过 1.35 这条线】,而 1px 抖动是必然的。
 *
 * 【误刹的后果是卡死,不是抖一下】解锁要 scale_r <= RESUME_R(1.15) 即 dist >= 1.30m。
 * 人实际站在 1.11m 时这个条件永远不成立 -> 车一直停着,除非人主动后退。
 *
 * 代价:真该刹车时晚约 2 帧(0.7s)。触发点 1.11m、巡航 1.1m/s,这个余量可以接受。
 * 【单帧耗时降下来后本值可以回调】判据:让 FRAMES x CH5 大致维持在 0.5~0.8s。 */
#define FOLLOW_NEAR_STOP_FRAMES    (2)

/*=========================== 大方位角减速 ===========================*/
/* 方位角超过此值(度)开始减速。满舵半径 1.39m，若目标在近处大角度，
 * 几何上根本转不过去，硬冲会冲过头。减速换取转向余量。 */
#define FOLLOW_BEARING_SLOW_DEG    (25.0f)

/* 方位角减速的最强档：到此角度(度)时速度压到 SLOW_MIN_RATIO。 */
#define FOLLOW_BEARING_MAX_DEG     (55.0f)

/* 2026-08-12 从 0.35 提到 0.40：配合 V_CRUISE_MS 降到 0.70。
 * 约束是 V_CRUISE × SLOW_MIN_RATIO > V_MIN_MS(0.25)，否则大方位角时
 * 会把速度压进堵转区。推导写在 V_CRUISE_MS 处。
 * 副作用：大角度下比以前少减一点速，但因为巡航速度本身降了 30%，
 * 绝对速度 0.28 m/s 仍远低于原来的 0.35 m/s，转向余量反而更宽。 */
#define FOLLOW_SLOW_MIN_RATIO      (0.40f)

/*=========================== 目标丢失 ===========================*/
/* 连续多少【拍】无效判为丢失。本模块 10ms 一拍 → 30 拍 = 0.3s。
 * 取 0.3s 是因为人正常摆臂遮挡板子约 0.1-0.2s，不能一遮就停。
 * 【单位坑，首版踩过】
 *   计数器加在 kart_follow_update() 里，走的是 10ms 调度拍，不是视觉帧。
 *   视觉 33ms 才出一帧，同一个无效结果会被连续读到 3 次。首版按"帧"
 *   写了 9，实际 0.09s 就判丢失，摆臂一挡就停 —— 正好把这条设计意图
 *   作废了。所以统一按拍计数，名字也从 FRAMES 改成 TICKS。 */
#define FOLLOW_LOST_TICKS          (30)

/* 丢失后的减速斜率(m/s per 10ms 拍)。0.06 → 0.3s 从 1.8 减到 0。
 * 不做急停：急停在倒车/湿滑地面上更容易失稳，缓停也来得及。 */
#define FOLLOW_LOST_DECEL          (0.06f)

/*=========================== 输出 ===========================*/
typedef enum
{
    KART_FOLLOW_IDLE = 0,      /* 未启动 */
    KART_FOLLOW_TRACKING,      /* 正常跟随：以 V_CRUISE 巡航 */
    KART_FOLLOW_HOLD,          /* 停着等：近距安全联锁触发（人太近），或斜坡已降到 0 */
    KART_FOLLOW_LOST           /* 目标丢失，正在减速停车 */
}kart_follow_state_enum;

typedef struct
{
    kart_follow_state_enum state;
    float  target_v_ms;        /* 建议目标速度(m/s)，>0 前进 */
    float  target_v_pulse;     /* 同上，换算成速度环量纲(脉冲/5ms)，直接喂 kart_control_set_target */
    float  target_delta;       /* 建议目标转角(计数)，已含中位偏置与软限位钳制 */
    int8   scale_level;        /* 尺度等级：-1=TOO_NEAR, 0=NORMAL, 1=TOO_FAR。
                                * LON_MODE=SCALE 时参与调速；=FIXED 时仅上报观测 */
    float  scale_r;            /* 原始 scale 比值，两种模式下都上报，调试看人车距离在怎么漂 */
    uint8  near_stop;          /* 1 = 近距安全联锁已触发（人太近），车正在停 */
    float  bearing_deg;        /* 方位角(度)，调试用 */
    float  bearing_filt;       /* 方位角滤波后(度)，实际控制用 */
    float  kappa;             /* 纯跟踪曲率(1/m)，调试用 */
    uint16 lost_ticks;         /* 当前连续无效拍数(10ms/拍)，不是视觉帧数 */
    uint8  saturated;          /* 1 = 打角顶到软限位，说明几何转不过来，需要减速或人别转太急 */
    uint8  confidence;         /* 视觉置信度0-255 */
}kart_follow_out_t;

