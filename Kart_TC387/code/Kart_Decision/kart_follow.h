/*********************************************************************************************************************
 * 文件名称  kart_follow
 * 所属分层  Kart_Decision（决策层：把视觉观测翻译成速度/转角指令）
 * 功能说明  "如影随形" 跟随控制律：黄色引导板方位/距离 → 目标速度 + 目标转角
 *
 * 【本模块只算，不下发】
 *   kart_follow_update() 只把结果写进内部结构体，由状态机决定要不要真的
 *   调 kart_control_set_target() / kart_steer_set_target_delta()。
 *   这样单测时可以把整条控制律跑一遍而不动车，也便于状态机在丢目标/急停时
 *   直接忽略本模块的输出。
 *
 * 【转角：纯跟踪，为什么不是 PID】
 *   目标不是"把方位角误差压到 0"，而是"沿一条能到达目标点的圆弧走"。
 *   纯跟踪直接给出这条圆弧的曲率：
 *       kappa = 2 * sin(beta) / L
 *   beta 是目标方位角，L 是到目标的直线距离（视觉直接给出，不用估）。
 *   本车已标定 R(m) * |delta| = 1480（实车日志复核：顺时转1圈中位 1466、
 *   科一录制 1434、科目四测试 1455、科四测2 1453，四条日志散布 ~3%），
 *   （这三个是历史日志【文件名】，不随本次科目四→科目三改名而变）
 *   而 kappa = 1/R，于是
 *       delta = 1480 * kappa
 *   纯跟踪的好处是它天然含前馈：目标越近、越偏，打角越大，不需要靠积分
 *   慢慢爬。对"跟着人走"这种目标点持续移动的场合，PID 的积分项反而会
 *   在人转向时滞后。项目里 kart_playback 的正向复现已经在用同一套换算，
 *   这里保持一致，不引入第二种打角口径。
 *
 * 【纵向：两套方案并存，编译期切，靠实车定】
 *   演进过程记录，避免以后重复踩：
 *     v1  距离 PID + 卡尔曼滤波   → 已删。绝对测距对身体挂载的柔性板不成立，
 *                                   滤波只是把错的值抹平，不会让它变准。
 *     v2  距离死区 ±0.3m          → 已删。同上，死区再宽也救不了错的测距值。
 *     v3  尺度比三档 ±0.3m/s      → 【保留】见 FOLLOW_LON_SCALE。
 *     v4  固定巡航速度            → 【保留】见 FOLLOW_LON_FIXED，当前默认。
 *
 *   v1/v2 是被证伪的（前提不成立），所以删。
 *   v3/v4 是取舍不同，都成立，所以都留着 —— 由 FOLLOW_LON_MODE 编译期二选一。
 *
 *   两者的分歧点是"距离这个自由度交给谁"：
 *     FIXED 交给人。人自带一个带宽和可靠性都远超单目尺度估计的距离控制器
 *           （眼睛 + 腿），而 scale_r 是整条视觉链里最脆的观测量。
 *           把最脆的量接进油门有速度自激振荡的风险。
 *     SCALE 交给车。人可以随便走，演示效果更好。
 *           振荡风险是理论推断，【实车没测过】，也许死区已经压住了。
 *
 *   默认 FIXED（先保证完赛），实车再试 SCALE 比较。
 *   两套都保留一个二值近距联锁当刹车，防人突然停下被顶。
 *
 * 【延迟预算（实测前的估算，接上硬件要用日志复核）】
 *       曝光+读出   33ms  (FPS_DEF=60, PCLK_DIV=2 → 实际 30FPS)
 *       调度相位    17ms  (10ms 任务平均等待 ~半个周期)
 *       图像处理     3ms  (160x120 单趟扫描)
 *       合计       ~53-60ms
 *   1.5m/s 时对应 9cm 的位置滞后，占 1.5m 前视距离的 6%。
 *   结论：视觉链路不是跟随速度的瓶颈，不需要为了提速去动帧率。
 *
 * 【速度：为什么上限定得比车的能力低】
 *   实车日志（mode=3 倒车复现）已经跑到 2.64 m/s 中位、2.76 m/s 峰值，
 *   所以车本身不慢。但跟随段是"跟着人走"，人的步速就是天花板，
 *   跟太快只会顶到人身上。所以这里按人的步速定上限（默认 1.8 m/s），
 *   真正要提速的是后面自动返程那一段，不在本模块。
 *
 * 【抓地 vs 几何：满舵在跟随速度下不会侧滑】
 *   需要的转弯半径 R = v²/a_lat。取 a_lat = 4.0 m/s²（与 kart_playback
 *   的 ALAT_DEFAULT 一致）：
 *       1.5 m/s → R = 0.56m      1.8 m/s → R = 0.81m
 *   而几何满舵半径是 1.39m（1480/1064），比上面两个都大 ——
 *   也就是说 v < 2.36 m/s 时几何先饱和，轮胎永远到不了打滑边界。
 *   跟随段不需要弯道限速逻辑。
 *
 * 修改记录
 * 日期              作者                备注
 * 2026-08-09        Kart                首版：纯跟踪 + 距离死区，未接硬件验证
 ********************************************************************************************************************/

