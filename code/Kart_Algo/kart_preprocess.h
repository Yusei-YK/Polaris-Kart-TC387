/*********************************************************************************************************************
 * 文件名称  kart_preprocess
 * 功能说明  图像预处理模块 - ROI裁剪 + 降噪 + 直方图均衡
 *
 * 设计目标：
 *   1. ROI裁剪：只处理图像下半部分（引导板出现区域），减少计算量
 *   2. 降噪：中值滤波或均值滤波，抑制传感器噪声和光照抖动
 *   3. 直方图均衡（可选）：改善不同光照条件下的颜色稳定性
 *
 * 性能约束：
 *   - 必须在帧间隔内完成（33ms@30fps），目标 <5ms 不阻塞控制环
 *   - 内存占用：原地处理或使用静态缓冲，避免动态分配
 *   - 可通过编译期开关选择性关闭各功能
 *
 * 使用方式：
 *   kart_vision_process() 之前调用 kart_preprocess_frame()，
 *   预处理后的图像仍存在原缓冲区（原地操作）或临时缓冲区。
 *
 * 作者：Claude Code  日期：2026-08-10
 ********************************************************************************************************************/

#ifndef KART_PREPROCESS_H_
#define KART_PREPROCESS_H_
#include "zf_common_headfile.h"

/* ======================== 编译期开关 ======================== */

/* 预处理模块总开关：=0 时整个模块编译为空壳，零开销 */
#define PREPROCESS_ENABLE          (0)  /* 回到原始 RGB565，先验证预处理是否制造假目标 */
#define PREPROCESS_WIDTH           (160)
#define PREPROCESS_HEIGHT          (120)

/* ROI裁剪：只处理图像下半部分（引导板通常出现在下方） */
#define PREPROCESS_ROI_ENABLE      (1)
#define PREPROCESS_ROI_Y_START     (41)    /* 0~40行清黑，41~119行参与滤波和识别 */

/* 降噪滤波：中值滤波（3x3窗口，鲁棒但慢）或均值滤波（3x3窗口，快但平滑） */
#define PREPROCESS_DENOISE_ENABLE  (1)
#define PREPROCESS_DENOISE_MEDIAN  (0)     /* =1 中值，=0 均值 */

/* 直方图均衡：对RGB565各通道分别均衡，改善光照不均（耗时较大，慎用） */
#define PREPROCESS_HIST_EQ_ENABLE  (0)

/* ======================== 数据结构 ======================== */

/* 预处理统计信息（性能监测用） */
typedef struct
{
    uint32 last_us;         /* 上一次预处理耗时（us） */
    uint32 max_us;          /* 历史最大耗时 */
    uint32 count;           /* 累计处理帧数 */
} kart_preprocess_stat_t;

/* ======================== 对外接口 ======================== */

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_preprocess_init
 * 功能说明  预处理模块初始化（清统计量，分配缓冲区）
 * 参数说明  void
 * 返回参数  void
 * 注意事项  必须在 vision_init() 之前调用
 *-----------------------------------------------------------------------------------------------------------------*/
void kart_preprocess_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_preprocess_frame
 * 功能说明  对一帧图像执行预处理（ROI + 降噪 + 均衡）
 * 参数说明  img      - 输入图像（RGB565，行优先）
 *           w        - 图像宽度（像素）
 *           h        - 图像高度（像素）
 * 返回参数  预处理后的图像指针（可能是原地修改后的 img，也可能是内部缓冲区）
 * 注意事项  - 返回指针的生命周期：到下一次调用 kart_preprocess_frame() 前有效
 *           - 若所有开关都关闭，直接返回 img 不做任何处理
 *           - ROI 裁剪后，返回的有效区域为 [ROI_Y_START, h)，调用方需注意坐标偏移
 *-----------------------------------------------------------------------------------------------------------------*/
const uint16 *kart_preprocess_frame(const uint16 *img, int16 w, int16 h);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_preprocess_get_stat
 * 功能说明  获取预处理统计信息
 * 参数说明  void
 * 返回参数  统计量结构体指针（只读）
 * 注意事项  可用于 VOFA 监测预处理耗时，判断是否成为性能瓶颈
 *-----------------------------------------------------------------------------------------------------------------*/
const kart_preprocess_stat_t *kart_preprocess_get_stat(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_preprocess_reset_stat
 * 功能说明  复位统计量
 * 参数说明  void
 * 返回参数  void
 *-----------------------------------------------------------------------------------------------------------------*/
void kart_preprocess_reset_stat(void);

#endif  /* KART_PREPROCESS_H_ */
