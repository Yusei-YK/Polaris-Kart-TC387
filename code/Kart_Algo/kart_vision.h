/* 处理一帧。img 指向 w*h 个 RGB565 像素（行优先）。
 * 纯计算、不阻塞,但【会改本模块的 static 状态,也不可重入】:除了写内部快照
 * (kart_vision_get() 取的就是它),连续性门还会记下本帧的 cx/cy/宽度和 hold
 * 计数给下一帧用,所以同一帧喂两次结果可能不同。
 *
 * 【耗时量级】图像访问约 1.3 遍：第一趟全图找种子 run，第二趟只走种子行上下相邻的行，
 * 一碰到连续空行超过 MAX_SKIP 就停。使用固定 160×120 三态掩膜，不用标号数组。
 * 老实现是 1 遍，多出来的 0.3 遍换掉的是「框永远满屏」，这笔账不用算。
 *
 * 【造图验证过的连通域行为（九种构造图，只验算法自身，不代表实拍）】
 *   单独的板子 100×73           → W=100 fill=100% 过
 *   板子 + 四角各一条 3px 的 run → W=100，框没被拉动（这正是老实现必满屏的那一条）
 *   板子 + 四个孤立单像素     → W=100，MIN_RUN 在源头就吃掉了
 *   板子 60 + 旁边第二块红 30  → W= 60，第二块被忽略（老实现会并成 130）
 *   板子 40 + 第二块更长 60    → W= 60 cx 落在第二块上，【跟错目标】
 *                                     已知失效形态，见上面限制 1，不是门限能拦的
 *   板子严重过曝 (31,22,23)   → W=100 过，老判据在这一档必漏
 *   斜置板子（剪切 0.5）       → W=104 fill=67%，带区间跟得上，没断在半截
 *                                     【斜置时填充率只剩 67%】这就是 MIN_FILL_PCT
 *                                     不敢开到 70 的原因，20 还有三倍余量
 *   斜的细长反光带               → fill=4%，reject=4 拦住
 *   全灰无目标                   → valid=0 reject=1
 *
 * 【测距公式的往返一致性(按现在的宏:板高 0.45m、FPX 83.5,正对光轴)】
 *   dist = 0.45 × 83.5 / 框高px,所以
 *       1.0m→37.6px→取整38px→0.99m   1.5m→25.1px→取整25px→1.50m   2.0m→18.8px→取整19px→1.98m
 *       3.0m→12.5px→取整13px→2.89m   4.0m→9.4px→取整9px→4.18m   6.0m→6.3px→取整6px→6.26m
 *   原来这里是按 0.71m 板、FPX 211 算的那一组(1.0m 对应 150px),那两个数
 *   现在的宏里都不存在了,已按 0.45m/83.5 重算。
 *   真实分辨率比原文差得多:4m 处 1px 值 0.42m(6m 处 0.89m);
 *   原文算成 4m 处 1px 才 0.11m,那是板更大、焦距更长时的数。
 *   另外 VISION_MIN_WIDTH(10) 已经把可用距离卡在 2.76m 内,
 *   所以 3m 以后那几行只用来验算公式,跑车时到不了。
 *   这些数字只说明"公式和整数实现没写错",不代表精度够用。 */
const kart_vision_result_t *kart_vision_process (const uint16 *img, int16 w, int16 h);

