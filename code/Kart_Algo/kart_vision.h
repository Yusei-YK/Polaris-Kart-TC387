/*********************************************************************************************************************
 * 文件名称  kart_vision
 * 所属分层  Kart_Algo。算法本身是纯整数运算,但【本模块不是无状态的】:
 *           kart_vision.c 里有 20 个文件级 static,其中
 *           vis_cont_cx/cy/w/hold/rej 是跨帧的连续性门状态 —— 同一帧图
 *           喂两次结果可能不同,所以 kart_vision_process() 不可重入、
 *           也依赖调用顺序。另外整个 .c 被 #pragma section all
 *           "cpu0_dsram" 定段(掩膜 19200B 放不进默认段),
 *           这条是 AURIX/TASKING 专有。
 * 功能说明  黄色引导板检测：一帧 RGB565 → 目标方位角 + 距离
 *
 * 流程：RGB565 → 整数 HSV 色相距离 → 三态掩膜 → 高置信种子带动宽松候选生长
 *       → 原始连通域测距 → 后置十字腐蚀核心定中心。
 *
 * 三态掩膜用于抗光照：颜色最稳定的像素负责起种子，阴影和高光边缘只作为候选并入，
 * 不能独立生成目标。腐蚀不放在生长前，避免远处、侧倾或过曝后变薄的板子被提前杀掉；
 * 原始区域保留真实宽度用于测距，腐蚀核心只压低边缘反光和毛刺造成的中心漂移。
 *
 * 已知边界：完全过曝成白色后没有色相；任何只看颜色的算法也无法区分两个同色物体。
 * 板子应使用硬质哑光黄色面、黑色边框，并尽量成为视野内最大的黄色物体。
 * VISION_FPX 已按竖板高度实测反算(见下面 VISION_FPX 的注释,运行区间取 83.5px),
 * 板宽高也已实量(0.33m × 0.45m);仍然缺实车标定的是四道几何门
 * (MIN_AREA / MIN_WIDTH / 宽高比 / 填充率),那四个数至今是估的。
 *
 * 修改记录
 * 日期              作者                备注
 * 2026-08-09        Kart                首版颜色分割
 * 2026-08-12        Kart                色相扇区 + 种子行传播
 * 2026-08-13        Kart                黄色三态掩膜 + 后置核心腐蚀
 ********************************************************************************************************************/

