#ifndef VISION_ENABLE
#define VISION_ENABLE              (0)
#endif

/*=========================== 像素格式：必须实测确认 ===========================*/
/* DMA 字节序和小端 uint16 叠加后无法只靠源码判断。当前实测黄色像素满足 R5、G5 高而
 * B5 低，证明 VISION_BYTE_SWAP=1 与当前相机一致；换相机后仍需用黄色板复查。 */
#ifndef VISION_BYTE_SWAP
#define VISION_BYTE_SWAP           (1)
#endif

#if (VISION_BYTE_SWAP == 0)
#define VISION_PIX(p)              (p)
#else
#define VISION_PIX(p)              ((uint16)(((uint16)(p) >> 8) | ((uint16)(p) << 8)))
#endif

/* RGB565 分量提取。R/B 是 5 位(0-31)，G 是 6 位(0-63)。
 * 为了让三个分量同标度，G 右移 1 位降到 5 位，判别式里统一用 5 位量。
 * 【别"修"这里的 >>6】G 在 RGB565 里占 bit10..bit5，取 6 位本该是 >>5 & 0x3F；
 * 写成 >>6 & 0x1F 是故意的，等于"取 6 位再除 2"，把 G 归到和 R/B 一样的 0-31 标度。
 * 色相判据靠三分量的差值，标度不统一会直接把色相算歪，这一条比以前更不能动。 */
#define VISION_R5(p)               ((uint8)((VISION_PIX(p) >> 11) & 0x1FU))
#define VISION_G5(p)               ((uint8)((VISION_PIX(p) >>  6) & 0x1FU))
#define VISION_B5(p)               ((uint8)( VISION_PIX(p)        & 0x1FU))

/*=========================== 黄色目标参数 ===========================*/
/* 色相圆分 6 个扇区，每扇区 42 格，全圆 252；1 格约 1.43 度。
 * 车载调试页已归一化到 G5，四组黄板样本得到 H30、H40、H42、H42。
 * PC 图传显示的是原始 G6，必须先右移一位：
 *   (22,46,0) → (22,23,0) → H44
 *   (20,42,0) → (20,21,0) → H44
 *   (23,47,0) → (23,23,0) → H42
 * 浅黄背景 (25,44,20) → (25,22,20) → H16。
 * 综合目标范围 H30~44，中心取 44，最大偏差 7；严格小于 8 的种子门覆盖全部样本。
 * 1.7m 实测出现 W17 但 H 只剩 1～4 的整行断裂，候选容差放到16；随后中心实测
 * dev=9，强种子门提高到10，保证典型黄板像素能起种，同时仍明显严于候选门。
 * 已测浅黄背景 H16，距中心 21 格且饱和度不足，候选门仍留 5 格色相余量。
 *
 * 中心 44 实测：板子 H45 S100 ok100，木地板 H28 S33 ok62，dev 分别是 1（余量
 * 9 格）和 16（出种子门；TOL 收到 16 后也出候选门）。
 * 【别把中心放到 37】那是零余量配置：板子 dev=8、地板 dev=9，双双小于种子门 10，
 * 而地板横贯画面 span=160 赢过板子 18px，选种子时选上地板 → width=160 大框、
 * hue_pct=39%、测距 0.45m 而人实站 1.5m → 近距保护锁存 → 车不走、方向盘原地扫。
 * 顺带排除：皮肤 H21~25 dev 19~23、水泥沙色 H31 dev 13。
 * 换板子或换场地后用菜单相机页的 HUE 读数行重新定中心，别拍脑袋。 */
#define VISION_HUE_FULL            (252)
#define VISION_HUE_SECTOR          (42)
#define VISION_HUE_CENTER          (44)
#define VISION_HUE_TOL             (16)
#define VISION_HUE_SEED_TOL        (10)
#define VISION_MIN_SAT_PCT         (25)

#if (VISION_HUE_SEED_TOL >= VISION_HUE_TOL)
#error "VISION_HUE_SEED_TOL must be lower than VISION_HUE_TOL"
#endif

/* 单像素最小亮度（三分量之和，5 位标度，上限 93）。低于此值认为是暗部噪声，直接弃。
 * 【色相判据下这一条比以前更必要】暗处 d = max-min 只有个位数，(G-B)/d 的量化噪声
 * 能把色相甩出几十格，不先卡亮度就会在阴影里随机检出色块。
 * 保留 9 不动：老值是实测挑的，且它挡的是同一个现象（低亮度下比值乱跳）。 */
#define VISION_MIN_SUM             (9)

/*=========================== 几何标定：全部需要实测 ===========================*/
/* 130度镜头按等距鱼眼 r=f*theta 建模，不对整帧重采样，只修正最终方位和距离。
 * 焦距按竖板高度实测反算：1.0m→84.4px，1.5m→80.0～83.3px，1.7m→83.1px，
 * 运行区间取 83.5px。0.55m 样本受近距畸变和测距误差影响，不参与主标定。
 * 标称视场角不能替代相机内参；这个值以后可用横向五点标定继续修正。 */
#define VISION_FPX                 (83.5f)

/* 引导板黄色区域实际尺寸。板子竖着固定在身上：宽 0.33m，高 0.45m。
 * 横向宽度用于焦距标定；运行时距离改用高度计算，因为走动时身体绕竖轴摆动主要压缩
 * 投影宽度，高度受影响更小。贴黑边或遮住边缘后，应填写实际可见黄色区域尺寸。 */
#define VISION_BOARD_W_M           (0.33f)
#define VISION_BOARD_H_M           (0.45f)

/*=========================== 掩膜尺寸 ===========================*/
/* 掩膜是定长静态数组，按 160×120 开。传进来的图超过这个尺寸就直接判"没看见"
 * （见 kart_vision_process），不截一部分算 —— 截了会给出一个看着正常、
 * 实际只覆盖左上角的结果，比明确失败危险。
 * 占用：掩膜 19200B + 两条行备份 320B，放 cpu0 DSRAM。 */
#define VISION_MASK_W              (160)
#define VISION_MASK_H              (120)

/*=========================== 连通域生长参数 ===========================*/
/* 这四个数决定「什么算团块的一部分」。

 * VISION_ERODE_ITER —— 连通域生长后的核心腐蚀遍数。
 *   原始连通域的框、面积和填充率不动，测距不会因腐蚀缩水；腐蚀后的核心只算中心，
 *   用来压掉边缘反光和单侧毛刺造成的质心漂移。核心被削空时退回原始质心。
 *   腐蚀绝不能放在种子搜索前，否则远处、侧倾和过曝后变薄的目标会先被杀掉。
 *
 * VISION_MIN_RUN —— 行内连续段的最小长度。
 *   它是区域生长前的横向基础噪声门；后置腐蚀只稳中心，不替它拒绝假区域。
 *   仍然【别往上调到 5 以上】：那会在远处把板子的上下边缘（斜边处 run 很短）啃掉。
 *
 * VISION_ROW_GAP —— 逐行传播时的区间容差(px)。
 *   下一行的 run 只要与「当前带区间左右各放宽 GAP」相交就并入。
 *   取 2：板子边缘斜置时相邻行的起止列会差 1-2 px，容差 0 会在斜边处断开生长，
 *   把一块板子长成上半截。放太大（>4）等于允许横向跨越空隙，
 *   又会把旁边独立的红块连过来，退化成老实现。
 *
 * VISION_MAX_SKIP —— 允许连续多少空行仍继续传播。
 *   远距离实测偶发只连出 2～6 行，说明量化噪声会让黄色区域产生断行。取 3 可跨过
 *   小裂缝；更大的竖向缺口不再连接，避免跨到另一块独立同色物体。 */
#define VISION_ERODE_ITER          (1)
#define VISION_MIN_RUN             (3)
#define VISION_ROW_GAP             (2)
#define VISION_MAX_SKIP            (3)

/*=========================== 有效性门限 ===========================*/
/* 【四道门的取值全部要重标，本次只是放宽到「明显不合理才拦」】
 * 老值是在「外接框恒满屏」的前提下拍的：那时 area 恒等于全图红像素数、
 * width 恒等于 160，四道门实际上从来没有在正常工况下起过作用，
 * 拿老值当基线是没有依据的。现在 area/width 第一次是团块真值，
 * 真正的取值必须实拍统计「板子在各个距离上的 area/宽高比/填充率」之后再定。
 * 在那之前这四个门只承担一件事：把明显不是板子的东西挡掉，不要参与精细判别。 */
#define VISION_MIN_AREA            (15)    /* 团块最小像素数。MIN_RUN 已经杀掉零散噪点，这里只挡「只剩一小截」 */
#define VISION_MIN_WIDTH           (10)    /* 最小外接框宽度(px)。
                                                 * 按现在的宏(板 0.33×0.45m、FPX 83.5)反解:框宽 w 对应框高 w×0.45/0.33。
                                                 * 10px 宽 → 框高 13.6px → dist 2.76m(±1px 为 2.51~3.06m),也就是这道门
                                                 * 顺手把可用距离压在 2.76m 以内。
                                                 * 门再放宽没有意义:4px 宽 → 框高 5.5px → dist 6.9m,宽只要差 ±1px,距离
                                                 * 就在 5.5~9.2m 之间跳。"测到了但数值没意义"比明确丢目标更坏:跟随环
                                                 * 会拿它当真。 */
/* 宽高比门限 ×10。竖板正对时 0.33/0.45 ≈ 0.73。
 * 下限 0.3 容许较大的左右偏转；上限 1.8 容许身体遮住部分上下边缘。
 * 超出后几何尺寸已经不适合继续给跟随控制使用。 */
#define VISION_ASPECT_MIN_X10      (3)
#define VISION_ASPECT_MAX_X10      (18)
/* 外接框填充率下限(%)。老值被调成 0（等于关掉），因为在「框恒满屏」下它恒不通过。
 * 现在框是单个团块的真实外接框，实心板子的填充率本该在 70% 以上，这道门重新有意义了。
 * 但只敢开到 20：印刷不均 + MIN_RUN 啃边 + 中间图案掉出饱和度门都会压低填充率，
 * 而它现在【不再承担】「相邻色块被并框」的兜底职责（种子生长只长一个团块）。
 * 它现在只挡一种东西：斜置的细长反光带（外接框大、实际像素少）。 */
#define VISION_MIN_FILL_PCT        (20)

/*=========================== 自适应回退：逆光鲁棒性的主力 ===========================*/
/* 【为什么需要它】绝对阈值在逆光下必死。逆光时整幅图的 S/V 一起塌，dev 全体抬高，
 * 一帧里可能没有任何像素满足 dev < SEED_TOL(10)，seed_y<0 直接整帧丢目标 ——
 * 哪怕板子还清清楚楚在画面里、还是全图最像黄色的那一块。
 *
 * 逐飞"暴晒/阴影/背光都能锁"那套的核心不是更好的阈值，是把判决从
 * 绝对(你的 dev 够小吗) 换成相对(全图谁的 dev 最小)。相对关系在逆光下还活着：
 * 板子的 S 从 200 掉到 60 时，它依然是画面里离黄色最近的那块。
 *
 * 所以只在【绝对门全军覆没】时才回退，分两级，一级不够再上二级：
 *   L1 相对种子：不重扫原图，直接在已有的 dev 图上取全图最小 dev，
 *                把种子门临时放到 min_dev+1（但绝不超过 ADAPT_SEED_MAX）。
 *   L2 宽松重建：连 L1 都没结果，说明像素根本没进 dev 图（被亮度门/饱和度门挡了），
 *                用放宽的亮度+饱和度门重建一次掩膜再来一遍。
 *
 * 【ADAPT_SEED_MAX 为什么是 12，这个数是整条改动的地基】
 * .h 上面那段已经记录了实测的干扰物色相偏差：
 *      板子(正常光) dev=1    水泥沙色 dev=13    木地板 dev=16    皮肤 dev=19~23
 * 12 严格低于水泥的 13 —— 所以哪怕回退到顶格，水泥/地板/皮肤依然一个都进不了种子，
 * 而板子只要在逆光下 dev 还 <= 11 就能被救回来。
 * 【别往上调过 12】13 就开始把水泥地面收进来，那正是 08-16 那次"选上木地板 →
 * width=160 大框 → 测距 0.45m → 近距保护锁存 → 车不走"的复现路径。 */
#define VISION_ADAPT_ENABLE        (1)
#define VISION_ADAPT_SEED_MAX      (12)

/* L2 宽松重建用的亮度/饱和度门。只在 L1 也失败时用一次。
 * MIN_SUM 9→6：暗部量化噪声会让色相乱跳，这是放宽的代价，靠 ADAPT_SEED_MAX 兜住。
 * MIN_SAT 25→15：逆光下板子饱和度实测会掉到 20% 以下，25 那道门就是它被挡的地方。 */
#define VISION_ADAPT_MIN_SUM       (6)
#define VISION_ADAPT_MIN_SAT_PCT   (15)

/*=========================== 连续性门：拒绝跳到第二个同色物体 ===========================*/
/* 【为什么需要它】.h 开头就承认了"任何只看颜色的算法都无法区分两个同色物体"，
 * 造图验证里也明确记着那条已知失效形态：板子 40px + 旁边第二块同色 60px
 * → 选种子时选上第二块、cx 落在错的物体上。颜色本身没有更多信息可用了，
 * 但【时间】上有：帧间隔只有 25~27ms，真目标不可能在一帧里跳走半个画面、
 * 也不可能一帧里宽度翻倍。跳变的那个必然是另一个物体。
 *
 * 这道门只在【上一帧刚锁定过】时才生效(锁还热)，锁凉了就不管，
 * 否则第一次起锁和真正丢失后的重捕获会被自己拦死。
 *
 * MAX_JUMP_PX 60：25ms 内目标中心在 160px 宽画面里移动 60px，
 *   等效横向角速度约 60/83.5 rad / 0.025s = 28 rad/s —— 人和车都到不了这个数。
 * SCALE_NUM/DEN 2/1 和 1/2：一帧内宽度翻倍或减半，物理上不可能，只能是换了物体。
 * HOLD_TICKS 24：约 600ms（2026-08-17 围挡纠缠实车问题以前发生过一次 430ms 遮挡，原 8 拍扛不住）。超过这个时长没锁定就放开限制，允许重新捕获任何位置的目标。 */
#define VISION_CONT_ENABLE         (1)
#define VISION_CONT_MAX_JUMP_PX    (60)
#define VISION_CONT_SCALE_NUM      (2)
#define VISION_CONT_HOLD_TICKS     (24)

/* 过曝判据:三个 5 位分量都 >= 该值。过曝像素的 max-min 被压平,饱和度门必然
 * 判死,色相无从谈起。纯诊断阈值,不参与任何检测判据。 */
#define VISION_OVER_LEVEL          (30)

/*=========================== 检测结果 ===========================*/
typedef struct
{
    uint8  valid;          /* 1 = 本帧检测到合法目标，其余字段才有意义 */
    float  bearing_rad;    /* 方位角(弧度)。>0 = 目标在车头右侧。已按 f_px 反投影，不是像素偏差 */
    float  dist_m;         /* 距离(米)。由外接框高度反算，精度随距离平方衰减 */
    int16  cx_px;          /* 团块质心列，用于画面调试 */
    int16  cy_px;          /* 团块质心行 */
    int16  width_px;       /* 外接框宽度，标定 f_px 时要读这个 */
    int16  height_px;      /* 外接框高度 */
    uint16 area_px;        /* 团块像素总数。【语义变了】老实现是全图同色像素数，
                            * 现在是【被并入种子团块的】像素数 —— 视野角落的孤立红像素
                            * 不再计入。所以换算法后这个数会明显变小，那是对的，
                            * 不要以为是识别变差了。MIN_AREA 也因此要重标。 */
    uint8  reject;         /* 无效原因:0 通过 1 面积不足 2 太窄 3 宽高比 4 填充率。
                            * 现场丢了目标先看这个值。
                            * 【3 是两件事共用一个值】除了真的宽高比不合,
                            * 连续性门拦掉"跳到另一个同色物体"时也报 3(kart_vision.c:1049),
                            * 因为 reject 取值不能新增(kart_menu.c 和标定页按四个值分支)。
                            * 要区分看 cont_reject 有没有在涨。 */
    uint8  confidence;     /* 四道门限余量里最低的那一项,当前只用于诊断/后续融合。
                            * 【有效帧上实际落在 80~255,不是 0~255】.c 末尾先取
                            * 面积/宽度/填充率/宽高比四项的最小值,再夹到 [80,255];
                            * 前三项本身就从 80 起步,宽高比项从 255 往下扣。
                            * 所以"分数低"要看它离 80 多近,不要按 0 起点读。 */

    /* 外接框的真实左上角。调试页画框必须用它，不能拿 cx-width/2 反推 ——
     * 质心是按同色像素加权的，外接框却是极值框，两者只在「单块且对称」时重合。
     * 恰好是最该看的情况会错开：板子被部分遮挡时质心偏向未被挡的那半。 */
    int16  box_x0;         /* 外接框最小列（min_x） */
    int16  box_y0;         /* 外接框最小行（min_y） */

    /* 逐像素统计(0~100%),【纯诊断】,不参与任何判据。检测失败时靠这三个数
     * 区分三种完全不同的病因,不然日志里只看到 reject=area,查不出为什么。
     *   dark_pct 高 → 欠曝,像素过不了 MIN_SUM 亮度门
     *   over_pct 高 → 过曝,分量压平后过不了 MIN_SAT_PCT 饱和度门
     *   两个都低而 hue_pct 仍为 0 → 曝光正常,是色相窗口(HUE_CENTER/TOL)不对,
     *                                或白平衡漂了把黄色搬出了窗口 */
    uint8  dark_pct;       /* 过不了亮度门的像素占比 */
    uint8  over_pct;       /* 过曝像素占比 */
    uint8  hue_pct;        /* 进了掩膜(色相合格)的像素占比 */

    /* 【纯诊断】自适应回退走到了哪一级 + 最小色相偏差。
     * 这两个数是逆光现场唯一能分开三种病因的东西：
     *   adapt_level=0 且 valid=1 → 绝对门就够，光照正常
     *   adapt_level=1            → 绝对门失守、靠相对种子救回来了(逆光已经在发生)
     *   adapt_level=2            → 连亮度/饱和度门都过不了，救回来靠的是宽松重建
     *   adapt_level=3            → 两级都没救回来，看 min_dev 判是"色相真的不对"
     *                              还是"色相对但整幅图都不达标"
     * min_dev 是全图最小色相偏差(127=没有任何像素算出过色相)。它直接告诉你
     * HUE_CENTER 偏没偏：板子在画面里而 min_dev 长期 > 20，就是中心值该重标了。 */
    uint8  adapt_level;    /* 0 正常 / 1 相对种子 / 2 宽松重建 / 3 全部失败 */
    uint8  min_dev;        /* 全图最小色相偏差(0~126)，127 = 无有效色相像素 */

    /* 【纯诊断】被连续性门拒绝的次数(累计，看差分)。
     * 涨得快 = 画面里确实有第二个同色物体在抢，或者 MAX_JUMP_PX 太紧。
     * 恒不涨而现场明显跟错了 = 这道门没起作用，查 cont_hold 是否一直是 0。 */
    uint16 cont_reject;

    /* 【纯诊断】min_dev 只说"色相算出来是多少"，这两个数说"那个色相还可不可信"。
     * 色相 42*(G-B)/d 分子分母都是差值，对曝光免疫；但 RGB 只有 5 位，
     * 曝光压到 1/5 时 d 从 20 掉到 4 —— 比值还在，可分辨级数没了，
     * ±1 量化噪声就能把色相甩出十几格。逆光的真正失效是位数不够，不是颜色变了。
     *   min_dev_d >= 12  位数够，色相可信，失效原因在别处
     *             5~10   临界，放宽亮度门(L2)有意义
     *             <= 4   信息已经没了，只能从相机侧或标志物侧解决
     * 取 min_dev 那个像素的 d 而不是全图最大 d：最大 d 会被背景高对比边缘占据。
     * mean_sum 是 AE 的行为探针 —— AE 就是把画面均值稳在目标上，所以逆光时
     * 它应当基本不动而 min_dev_d 塌掉，那就是背光欠曝的判定式。
     * 【为何不直接读相机曝光】scc8660_get_parameter() 要借 UART1 9600,
     * 运行时调它既抢外设又阻塞。注意不是"init 后已还给灯板"——
     * kart_camera.c:226 写明这条链路根本不需要还:UART1 静态归
     * 灯板,由 dot_matrix_screen_init() 配成 2Mbps,摄像头只是初始化时借用过。 */
    uint8  min_dev_d;      /* min_dev 那个像素的 max-min(0~31)，255 = 无有效色相像素 */
    uint8  mean_sum;       /* 全图 (R5+G5+B5) 均值(0~93) */
}kart_vision_result_t;

