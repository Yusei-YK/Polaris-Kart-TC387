/* ROI 色相统计（标定用）。在以 (cx,cy) 为中心、边长 side 的方块里逐像素统计。
 *
 * 【为什么要它】现场换一块板子（或者换个颜色、换个光照）以后，唯一真正需要知道的数
 * 就是"这台相机现在看到的这块板子，色相是多少"。单像素准星（probe_pixel）给的是一个点，
 * 一个点会撞上印刷网点、反光斑、JPEG 块噪声；标定要的是一片区域的中位数。
 *
 * 中位数而不是均值：均值会被区域边缘扫到的背景像素拉走，中位数不会（只要背景占比 < 50%）。
 *
 * 输出直接对应两个宏：med_hue -> VISION_HUE_CENTER，
 * p10/p90 的散布 -> 判断 HUE_TOL 够不够宽（经验：TOL 取 (p90-p10)/2 + 4 的余量）。 */
typedef struct
{
    int16  med_hue;      /* 色相中位数(0~251)。-1 = 有效样本不足，别拿它填宏 */
    int16  p10_hue;      /* 10% 分位，看散布 */
    int16  p90_hue;      /* 90% 分位 */
    uint8  ok_pct;       /* 过了亮度+饱和度门、色相有定义的像素占比 */
    uint8  dark_pct;     /* 区域内过不了亮度门的占比 */
    uint8  lowsat_pct;   /* 区域内过不了饱和度门的占比（含灰白） */
    uint8  med_sat_pct;  /* 饱和度中位数(%)，判断 MIN_SAT_PCT 留了多少余量 */
    int16  med_sum;      /* 亮度和中位数(0~93)，判断曝光是否合适 */
    int16  n_total;      /* 区域像素总数 */
}vision_roi_stat_t;

/* 统计一个方块 ROI 的色相分布。img/w/h 同 process；side 会被夹到 [3, 31] 的奇数。
 * 纯计算，不写任何全局状态，可在菜单页直接对着 scc8660_image 调。 */
void   vision_roi_stat (const uint16 *img, int16 w, int16 h,
                             int16 cx, int16 cy, int16 side,
                             vision_roi_stat_t *out);

/* 取某个像素的判别中间量，给摄像头调试页的取样十字用。
 * 存在的理由：现场「认不到板子」只有两种原因 —— 颜色没过判别式，或者过了但被
 * 面积/宽高比/填充率门限拒了。后者 reject 字段已经说清楚，前者不给中间量只能盲猜。
 *
 * 【m_lhs / m_rhs 的含义换了，但读法没换】
 *   m_lhs = VISION_HUE_TOL   （容差，恒定值）
 *   m_rhs = 本像素的色相偏差格数   （离目标色相中心多少格，1 格 ≈ 1.43°）
 *   仍然是"lhs > rhs 才算通过",调试页那句 "M%6ld >%6ld" 一个字都不用改,
 *   按现在的 VISION_HUE_TOL(16)显示出来就是「容差 16 > 偏差 3」
 *   (原文举的是容差 6 的例子,那是 TOL 还等于 6 时写的)。判据在 .c 里也写成
 *   严格小于,两处一致。
 *
 * 【m_rhs 等于 252 是一个哨兵值】表示这个像素被亮度门或饱和度门挡掉了，
 * 色相根本没参与判断（灰白、暗部、以及三分量相等无法定义色相的情形）。
 * 252 是色相圆周长，真实偏差永远到不了 —— 这样显示的两个数和返回值必然同向，
 * 不会出现「屏上看着过、检测器判不过」。sum 低于 MIN_SUM 时调试页另有 DARK 标记，
 * 两者叠加就能区分「太暗」和「不够鲜艳」。
 *
 * 【关键】这里必须复用 vision_hue_hit 的同一套整数运算，不能在调试页照抄公式：
 * 抄一遍就是两份实现，改阈值时漏改一处，调试页显示「通过」而检测器判「不通过」，
 * 那比没有这个页面更坏。
 *
 * 出参可传 NULL 表示不关心。返回值就是检测器的真实判定。 */
uint8  kart_vision_probe_pixel (uint16 pix, int16 *r5, int16 *g5, int16 *b5,
                                int32 *m_lhs, int32 *m_rhs, int16 *sum);

