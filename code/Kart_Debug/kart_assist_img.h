/*********************************************************************************************************************
 * 文件名称  kart_assist_img
 * 功能说明  逐飞助手图传(有线 UART_0 / P14.0-P14.1)。只为一件事存在:
 *           把原始 RGB565 帧送到上位机,用助手的"图片颜色识别"取色,
 *           反推 kart_vision.h 里的 VISION_HUE_CENTER/HUE_TOL/MIN_SAT_PCT
 *           与 MIN_SUM。(2026-08-12 判据换成色相扇区,原注释里的
 *           R_NUM/R_DEN 两个宏已删除。)
 *
 * 【为什么不用 kart_wifi 那条路】
 *   kart_wifi 走 WIFI_SPI,而 WIFI_ENABLE=0 且比赛不带无线模块。
 *   标定要的是"插上下载器就能看图",UART_0 是板上现成的 P14.0/P14.1。
 *
 * 【为什么本文件发送 V2 的 12 字节头】
 *   实测旧协议每帧都是完整的：旧帧头 AA 02 60 08 A0 00 78 00，连续三个
 *   帧头间距严格为 38408 字节，说明串口、波特率和像素长度都没有丢包。
 *   但助手 V2.0.0.6 只统计字节，宽高始终停在 10x10。对照用户提供的
 *   “V2版本例程/TC387_demo”后确认：该例程使用新版 12B CAMERA 配置头，
 *   格式为 head/checksum/cmd/type/width/height/data_type/reserve；本工程
 *   Libraries/zf_components 中仍是旧版 8B 图传协议。因此这里只在图传
 *   适配层发送 V2 头，不整体替换逐飞库，避免影响已有参数调试功能。
 *
 *   UART_0 @460800 整帧约 0.84 秒的发送时间，已按 AIMG_CHUNK_BYTES
 *   分块摊到主循环空转段，单次阻塞 ≈2.8ms；仍【只在 MISSION_IDLE 用】。
 *   行驶时不会产生新请求；这是调试功能，不是比赛运行时功能。
 *
 * 【为什么要把帧拷出来】
 *   连续发送一帧约 0.84 秒。若这期间 hold 住摄像头帧，视觉处理拿不到新帧；
 *   若不 hold 又直接发送 DMA 缓冲，DMA 会在发送途中覆写，发出去的图上半是新帧
 *   下半是旧帧 —— 拿这种撕裂图去标颜色阈值会得出完全错误的结论
 *   (会以为板子颜色在变),而标定恰恰是本模块唯一的用途。
 *   代价 38400 字节,而且【记在 cpu1 的 DSRAM 上,不是 cpu0】——
 *   实现里用 #pragma section all "cpu1_dsram" 单独把 img_buf 挪过去了,
 *   因为 cpu0 还要装 scc8660_image、preprocess_buf、金字塔和掩膜,240K 装不下。
 *   只在 AIMG_ENABLE=1 时占。
 *
 * 【与 debug/log 共用 UART_0 的约定】
 *   本模块直接 uart_write_buffer(UART_0, ...),不走 debug_send_buffer,
 *   也不调旧版 seekfree_assistant_interface_init() —— 那个函数会把库里的
 *   transfer/receive 回调指到 DEBUG_UART,而 kart_wifi 在 ENABLE 时也会设它,
 *   两处抢同一组全局回调。本模块不需要回调(不用示波器、不收参数),
 *   干脆不碰,少一个耦合点。
 *   UART_0 当前无设备:LOG_ON_UART0=0(日志在 UART_10),
 *   TLD7002 已飞线到 UART1,isr.c:231 只做丢弃兜底。
 *
 * 【已知风险(实测未验证)】
 * 【已知风险(实测未验证)】
 *   历史上给 TLD7002 挪线时记录过一次 "UART0 实测收发不通"(ERR=1/RX=0/回环 0)。
 *   原始记录现在在 board_pins.h 里 LOG_ON_UART0 定义上方那段(第三条),
 *   那里同时说明:那次是灯板 2M 半双工用法,与本处 460800 单向 TX 不同,未必同因。
 *   本模块正是"单向 TX"这一情形,所以值得一试;
 *   若助手仍收不到图,先看 g_aimg_img_sent 是否在涨:
 *     涨了 = 387 侧发出去了,问题在线/波特率/上位机;
 *     不涨 = 卡在请求阶段,看 g_aimg_img_skip 与相机帧。
 *   (UART_0 上没挂设备:LOG_ON_UART0=0,日志在 UART_10;TLD7002 已飞线到
 *    UART1,isr.c 里那段 UART_0 接收只做丢弃兜底。)
 *
 * 作者:Claude Code  日期:2026-08-12
 ********************************************************************************************************************/

#ifndef KART_ASSIST_IMG_H_
#define KART_ASSIST_IMG_H_
#include "zf_common_headfile.h"

/*=========================== 总闸 ===========================*/
/* 1 = 编译进来并占 38400 字节 cpu1 DSRAM(不占 cpu0);0 = 全部函数编译期空壳,零开销。
 * 标定完请改回 0 —— 这是调参设施,不是跑车功能。
 * 标定完请改回 0 —— 这是调参设施,不是跑车功能。
 *
 * 【2026-08-15 置 0】科三跟随段实测漏拍 15146(=75.7s),而 CH25
 * (分发耗时)全程最大仅 257us —— 卡死在 exec_us 计时窗之外的
 * 空转段,即本模块的阻塞整帧写。漏拍量子实测 ~72 拍 = 360ms。
 * 后果:5ms 标定的转向内环退化成 ~5Hz,录进去的轨迹本身就是脏的。 */
#ifndef AIMG_ENABLE
#define AIMG_ENABLE                (0)
#endif

/* UART_0 @460800 发送一帧约需 0.84s。
 * 【这个宏由 cpu0_main.c 执行,本文件不读它】50ms 任务里累 aimg_elapsed_ms,
 * 到了就调一次 request,所以真实颗粒度是 50ms 的整数倍(100 = 2 拍),
 * 而且那段本身也裹在 #if AIMG_ENABLE 里。
 * 发送忙时 request 会直接拒绝,不排队,因此每帧完成后能尽快取得一张新图。 */
#define AIMG_PERIOD_MS             (100u)

/* 【为什么要交换字节】屏上画面正常、助手上却是花的（亮点仍白、暗处仍黑、
 * 中间调全乱，且宽高/帧长/速率都正常）—— 这是 RGB565 高低字节错位的特征：
 * 0xFFFF 和 0x0000 交换后不变，其余全变。
 * 屏上正常说明 kart_vision 的 BYTE_SWAP=1 是对的，缺这一步的是本模块：
 * 以前直接把 scc8660_image 的原始字节送出去。
 *
 * 【为何不能将就】标定要在助手上取色，取到的必须和视觉算法看到的是同一个颜色。
 * 字节错位下红蓝是反的，抄下来的 RGB 整个是反的，拿它去定色相容差会得出错的结论。
 *
 * 与 kart_vision.h 的 VISION_BYTE_SWAP 是同一件事的两端，
 * 两边应同时为 1 或同时为 0；改一边时记得回来看这里。 */
#ifndef AIMG_BYTE_SWAP
#define AIMG_BYTE_SWAP             (1)
#endif

/* 单次 background_poll 最多发多少字节。
 * 【为什么必须分块】原来一次把 12+38400 字节全发完，UART_0 是全阻塞写，
 * 主循环 0.84 秒回不到 tick 分发 —— 10ms 拍的按键采样跟着停 0.84 秒。
 * 而 IDLE 下每 100ms 就请求一帧，等于按键常年被压着，整个菜单（包括首页）
 * 都表现为"按一下等好几秒"。这就是 2026-08-13 现场那个卡顿。
 * 现在每次只发一块就返回，块与块之间主循环照常跑拍。
 * 128B @460800 ≈ 2.8ms，小于 5ms 控制窗口；代价是整帧要 1.5 秒上下。
 * 盯 g_aimg_chunk_max_us：超过 4000 就把这个数减半。 */
#ifndef AIMG_CHUNK_BYTES
#define AIMG_CHUNK_BYTES           (128u)
#endif

/*=========================== 参数 ===========================*/
/* 图传用的串口。固定 UART_0 = P14.0(TX)/P14.1(RX),就是下载器那两个脚。
 * 【不要改成 UART_10】那是 VOFA/日志口,一帧图会把波形冲成乱码。 */
#define AIMG_UART                  (UART_0)

/*=========================== 诊断量 ===========================*/
/* 前两个是只增计数,后四个是状态量(会被清零/覆盖),看趋势时别混用。
 * 【只有全量档才有通道】g_aimg_busy 挂在 VOFA 第 12 路,但那是 LOG_PROFILE_S3=0
 * 的全量档(51 路);出厂档 LOG_PROFILE_S3=1(43 路)第 12 路是目标距离,
 * 整档一路 g_aimg 都没有。想在出厂档看图传状态得自己加通道。
 * 其余五个当前没有任何日志通道,想看得自己加。查问题的第一现场。 */
extern volatile uint32 g_aimg_img_sent;     /* 发完整帧数 */
extern volatile uint32 g_aimg_img_skip;     /* 请求被拒次数(上帧未发完/无新帧) */
extern volatile uint32 g_aimg_img_ms;       /* 上一整帧耗时(ms) */
extern volatile uint32 g_aimg_chunk_max_us; /* 单块发送的最坏耗时(us),不是整帧 —— 整帧看 g_aimg_img_ms */
extern volatile uint8  g_aimg_busy;         /* 1 = 正在发,菜单可据此显示进度 */
extern volatile uint32 g_aimg_progress;     /* 已发字节数,给菜单画进度 */

/*=========================== 接口 ===========================*/

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_assist_img_init
 * 功能说明  清零状态与计数，并把下载器 UART_0 配成
 *           460800 8N1 / P14.0(TX) / P14.1(RX)。
 * 参数说明  void
 * 返回参数  void
 * 注意事项  必须在 debug_init() 之后调，由这里最后一次配置 UART_0。
 *-----------------------------------------------------------------------------------------------------------------*/
void kart_assist_img_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_assist_img_request
 * 功能说明  请求发一帧。只做拷帧(含字节交换) + 置状态机,不发送。
 * 参数说明  void
 * 返回参数  1 = 已受理;0 = 被拒(上一帧还在发,或此刻没有新的相机帧)
 * 注意事项  可以在按键处理里调。真正的发送在 background_poll。
 *-----------------------------------------------------------------------------------------------------------------*/
uint8 kart_assist_img_request(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_assist_img_background_poll
 * 功能说明  有待发帧时推进一块（V2 头或一段图像数据）；空闲时立即返回。
 * 参数说明  void
 * 返回参数  void
 * 注意事项  【只能在主循环空转段调】单次 ≈2.8ms,整帧要调数百次;
 *           绝不能在 5ms 控制拍或中断里调用。
 *           【MISSION_IDLE 这一条本函数自己会挡】一旦发现不在 IDLE,
 *           就把状态机拍回 IDLE、丢掉没发完的半帧再返回 —— 不靠调用方记得。
 *           (kart_wifi 的同名函数没有这道自检,别把两边的习惯混起来。)
 *-----------------------------------------------------------------------------------------------------------------*/
void kart_assist_img_background_poll(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_assist_img_is_busy
 * 功能说明  是否正在发送。
 * 参数说明  void
 * 返回参数  1 = 正在发
 *-----------------------------------------------------------------------------------------------------------------*/
uint8 kart_assist_img_is_busy(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 函数名称  kart_assist_img_abort
 * 功能说明  放弃当前帧,状态机回 IDLE。退出标定页时调,避免离开页面后
 *           后台还在慢慢发半帧(上位机会显示花屏,让人误判成协议错)。
 * 参数说明  void
 * 返回参数  void
 *-----------------------------------------------------------------------------------------------------------------*/
void kart_assist_img_abort(void);

#endif  /* KART_ASSIST_IMG_H_ */
