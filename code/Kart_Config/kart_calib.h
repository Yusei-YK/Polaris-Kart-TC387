/* ==================================================================
 * 一、车辆几何(实测)
 * ================================================================== */
#define KART_WHEEL_DIAMETER_M       (0.240f)    /* 后轮直径,实测 240mm */
#define KART_WHEEL_TRACK_M          (0.60f)     /* 后轮轮距 */
#define KART_WHEELBASE_M            (0.62f)     /* 轴距 */
#define KART_MASS_KG                (22.0f)     /* 整车质量 */
/* 转弯半径常数:R(mm) × |delta(计数)| ≈ 本值 × 1000。
 * 【直接用法(单位已凑好)】R(m) = 本值 / |delta| ;某半径要的打角 = 本值 / R(m)。
 *   例:满舵 1064 → 1480/1064 = 1.39m;要 3m 半径 → 1480/3 ≈ 493 计数。
 * 标定来源:遥控日志逐拍 ds/dyaw 积分,打死稳态段实测 ——
 * 顺时针 -987→R=1.484m、逆时针 +1099→R=1.394m、右转 -1000→1.431/1.512m、
 * 左转 +1100→1.316m,左右散布仅 ±4%。 */
#define KART_STEER_R_TIMES_DELTA    (1480.0f)

/* ==================================================================
 * 二、电机与编码器极性
 * ------------------------------------------------------------------
 * 只在"接线换了/驱动板换了"时动。改之前先想清楚是接线反了还是
 * 控制环符号反了 —— 后者在第六节。
 * ================================================================== */
#define KART_STEER_MOTOR_SIGN       (+1)
#define KART_LEFT_MOTOR_SIGN        (+1)
#define KART_RIGHT_MOTOR_SIGN       (+1)

#define KART_LEFT_ENCODER_SIGN      (+1)
#define KART_RIGHT_ENCODER_SIGN     (-1)

/* ==================================================================
 * 三、编码器尺度(换轮子/换编码器必改)
 * ------------------------------------------------------------------
 * 2026-07-24 换新左编码器后重新标定(左右轮分别手掰十圈,大缓冲抓全):
 *   左十圈累计 20481、右十圈累计 20489 → 均≈2048 脉冲/圈(512 线×4 正交),
 *   左右 PPR 一致(比 1.0004),排除编码器量纲差异是起步打滑主因。
 *   后轮实测直径 240mm → 周长 π×0.240 = 0.753982 m,
 *   PULSE_TO_M = 0.753982 / 2048 = 0.00036816 m/脉冲。
 *   (旧值 0.00038777 偏大约 5.3%,里程会高估;
 *    手推 5m 那次标定因 20s 采样窗口截断作废,别再用那个方法。)
 *
 * 【别为了凑距离去动这两个值】它们是科目一录制/复刻共用的尺度,
 * 改了整条路径的比例都变。科目二那种"前行十米"裁判不量尺,改行程宏就行。
 * ================================================================== */
#define KART_ENCODER_PPR            (2048)      /* 每圈脉冲(512 线 × 4 正交) */
#define KART_LEFT_ENC_PULSE_TO_M    (0.00036816f)
#define KART_RIGHT_ENC_PULSE_TO_M   (0.00036816f)

/* 后轮减速比 40:20,标定真实车速时用 */
#define KART_REAR_GEAR_RATIO        (2.0f)

/* ==================================================================
 * 四、转向绝对编码器零位与硬限位(换齿轮/换转向编码器必改)
 * ------------------------------------------------------------------
 * 2026-07-30 换齿轮+编码器+转向电机后重标(CH14 平台值,已解 4096 环绕):
 *   左死 1248、右死 3176(相对中值 -1084)、中值取几何中点 164
 *   (手停读数 192/177 吻合)。行程 +1078/-1084 基本对称。
 *
 * 【注意】中值贴着 raw 0,CH14 在中值附近会在 0/4095 之间跳,这是正常的;
 *   delta 由 kart_steer_abs_wrap_delta() 做 mod-4096 修正,
 *   除显示外没有代码直接比较 raw。
 *
 * 【重标步骤】① 手推方向盘到左硬限位,读 CH14 平台值 → LEFT_LIMIT_RAW;
 *   ② 推到右硬限位读 → RIGHT_LIMIT_RAW;③ 中值取两者几何中点 → CENTER_RAW。
 *   软限位、外环上限、满舵半径全部自动跟随,不用再改别处。
 * ================================================================== */
#define KART_STEER_ABS_RAW_FULL         (4096)  /* 12bit 绝对编码器一圈计数 */
#define KART_STEER_ABS_CENTER_RAW       (164)   /* 中位(几何中点) */
#define KART_STEER_ABS_LEFT_LIMIT_RAW   (1248)  /* 最左硬限位 raw */
#define KART_STEER_ABS_RIGHT_LIMIT_RAW  (3176)  /* 最右硬限位 raw(过 0 环绕) */

/* --- 派生:硬限位相对中位的行程(计数,左正右负) ---
 * 右限位 raw 大于中位是因为过 0 环绕,故减一整圈折回负值。
 * 当前值:左 +1084 / 右 -1084,总行程 2168。
 * 【若日后重标后右限位不再环绕(raw < CENTER),把下面那个 -RAW_FULL 去掉】 */
#define KART_STEER_TRAVEL_L         (KART_STEER_ABS_LEFT_LIMIT_RAW  - KART_STEER_ABS_CENTER_RAW)
#define KART_STEER_TRAVEL_R         (KART_STEER_ABS_RIGHT_LIMIT_RAW - KART_STEER_ABS_CENTER_RAW - KART_STEER_ABS_RAW_FULL)

/* 软限位留的机械余量(计数):别顶到硬限位磨电机/打齿 */
#define KART_STEER_LIMIT_MARGIN     (20)

/* --- 派生:目标转角软限位。当前 +1064 / -1064,满舵半径 1480/1064 = 1.39m --- */
#define KART_STEER_DELTA_LIMIT_L    (KART_STEER_TRAVEL_L - KART_STEER_LIMIT_MARGIN)
#define KART_STEER_DELTA_LIMIT_R    (KART_STEER_TRAVEL_R + KART_STEER_LIMIT_MARGIN)

/* --- 派生:满舵转弯半径(米),给剖面/摆位算几何用。当前 1480/1064 = 1.39m --- */
#define KART_STEER_MIN_RADIUS_M     (KART_STEER_R_TIMES_DELTA / (float)KART_STEER_DELTA_LIMIT_L)

/* 转向中位偏置(计数):车"真正走直"的 delta 若不在 0,在这里补。
 * 标定方法(遥控日志离线回归 —— 这车固定打角走不直,量不出来):
 *   取 |delta|<450 的行驶采样,逐拍算曲率 c = Δyaw/Δs,对 delta 线性回归,
 *   零曲率截距即偏置。旧齿轮时四条日志得 -28.4/-27.8/-13.1/-62.4,汇总 -31.4。
 * 2026-07-30 重标后为 0:新中值 164 就是硬限位几何中点,左右软限对称,
 *   不需要补。若实测转圈左右半径差 >5cm 再重新标。
 * 【符号约定】下发值 = 期望转角 + 本值。往负调=车更偏左。 */
#define KART_STEER_CENTER_OFS       (0.0f)

/* ==================================================================
 * 五、单位换算(派生,不要手改)
 * ------------------------------------------------------------------
 * 速度环内部量纲是"编码器脉冲/5ms"。剖面规划、加速度、抓地极限这些
 * 只有在 m/s 下才有物理意义,靠这两个宏来回换。
 * ================================================================== */
#define KART_CTRL_PERIOD_S          (0.005f)    /* 速度环采样周期(秒),与 5ms 中断一致 */
/* 当前值:0.00036816 / 0.005 = 0.073632 m/s per (脉冲/5ms) */
#define KART_PULSE_V_TO_MS          (KART_LEFT_ENC_PULSE_TO_M / KART_CTRL_PERIOD_S)
#define KART_PULSE_MS_TO_V          (KART_CTRL_PERIOD_S / KART_LEFT_ENC_PULSE_TO_M)

