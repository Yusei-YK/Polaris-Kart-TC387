//工程导入到软件之后，应该选中工程然后点击refresh刷新一下之后再编译
//工程默认设置为关闭优化，可以自己右击工程选择properties->C/C++ Build->Setting
//然后在右侧的窗口中找到C/C++ Compiler->Optimization->Optimization level处设置优化等级
//一般默认新建立的工程都会默认开2级优化，因此大家也可以设置为2级优化

//对于TC系列默认是不支持中断嵌套的，希望支持中断嵌套需要在中断内使用enableInterrupts();来开启中断嵌套
//简单点说实际上进入中断后TC系列的硬件自动调用了disableInterrupts();来拒绝响应任何的中断，因此需要我们自己手动调用enableInterrupts();来开启中断的响应。

uint16 encoder_data;

int core0_main(void)
{
	get_clk();//获取时钟频率  务必保留

	//角度编码器初始化
    encoder_init_spi();
	//用户在此处调用各种初始化函数等
	IfxCpu_emitEvent(&g_cpuSyncEvent);
	IfxCpu_waitEvent(&g_cpuSyncEvent, 0xFFFF);
	enableInterrupts();

	while (TRUE)
	{
        encoder_data = encoder_angle_spi();                         // 使用SPI获取绝对值编码器数据
        printf("\r\nAbs Encoder data: %d.", encoder_data);          // 串口输出采集到数据
        systick_delay_ms(STM0,100);                                 // 时间间隔 100ms
	}
}



